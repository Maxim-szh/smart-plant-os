"""Generate the browser catalogue and firmware stage validation from one registry."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def outputs():
 data=json.loads((ROOT/'data/knowledge-base/profiles.json').read_text())
 codes=['seed','grow','flower','fruit','adult','rest']; masks={g:sum(1<<codes.index(s[0]) for s in stages) for g,stages in data['stages'].items()}
 ids={p['id']:p for p in data['plants']};assert len(ids)==len(data['plants'])
 for p in data['plants']:
  assert re.fullmatch(r'[a-z0-9-]{1,40}',p['id']) and p['group'] in masks and p['source'].startswith('https://')
 for alias in data['aliases']:assert re.fullmatch(r'[a-z0-9-]{1,40}',alias)
 rows=[(p['id'],masks[p['group']])for p in data['plants']]+[(alias,masks[ids[target]['group']])for alias,target in data['aliases'].items()]
 header='/* Generated by tools/generate_plant_profiles.py; do not edit. */\nstatic const struct { const char *id; unsigned mask; } profile_masks[] = {\n'+''.join('    {"%s", %du},\n'%row for row in rows)+'};\n'
 js="'use strict';\n/* Generated from data/knowledge-base/profiles.json. */\nwindow.SPPlantData="+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
 return {'firmware/components/sp_core/sp_plant_profiles.inc':header,'web/plant-data.js':js}
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 for path,text in outputs().items():
  file=ROOT/path
  if args.check:
   if not file.is_file() or file.read_text()!=text:raise SystemExit('Out of date: '+path)
  else:file.write_text(text)
 print('PASS: shared plant catalogue and stage masks')
