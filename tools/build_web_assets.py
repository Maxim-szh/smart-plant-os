#!/usr/bin/env python3
"""Build deterministic static HTTP variants; no run-time compression or secrets."""
import argparse,gzip,hashlib,re
from pathlib import Path

def build(web,cmake,source):
    symbols=dict((b,a) for a,b in re.findall(r'extern const uint8_t (\w+)_start\[\] asm\("_binary_(\w+)_start"\)',source))
    files=re.findall(r'target_add_binary_data\(\$\{COMPONENT_LIB\} "../../../web/([^"]+)" BINARY\)',cmake)
    out=['/* Generated by tools/build_web_assets.py. Do not edit. */',
         'typedef struct { const uint8_t *raw; const uint8_t *gzip; size_t gzip_size; const char *raw_tag, *gzip_tag; } sp_web_asset_t;']
    rows=[];summary=[]
    for name in files:
        raw=(web/name).read_bytes();symbol=symbols[re.sub(r'[^a-zA-Z0-9_]','_',Path(name).name)]
        packed=gzip.compress(raw,compresslevel=9,mtime=0) if Path(name).suffix in ('.html','.js','.css','.webmanifest') else b''
        if packed and len(packed)>=len(raw):packed=b''
        tag=lambda data:'\\"'+hashlib.sha256(data).hexdigest()+'\\"'
        if packed:
            out.append('static const uint8_t sp_gz_'+symbol+'[] = {')
            out.extend(','.join(str(b) for b in packed[i:i+24])+',' for i in range(0,len(packed),24));out.append('};')
        rows.append('{'+f'{symbol}_start, '+(f'sp_gz_{symbol}, sizeof(sp_gz_{symbol})' if packed else 'NULL, 0')+f', "{tag(raw)}", "{tag(packed) if packed else tag(raw)}"'+'}')
        summary.append((name,len(raw),len(packed) if packed else len(raw)))
    out.append('static const sp_web_asset_t sp_web_assets[] = {\n'+',\n'.join(rows)+'\n};')
    return '\n'.join(out)+'\n',summary

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--web',type=Path,required=True);p.add_argument('--cmake',type=Path,required=True);p.add_argument('--source',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    content,summary=build(a.web,a.cmake.read_text(),a.source.read_text());a.output.parent.mkdir(parents=True,exist_ok=True)
    if not a.output.exists() or a.output.read_text()!=content:a.output.write_text(content)
    print('Static assets:',sum(x[1] for x in summary),'->',sum(x[2] for x in summary),'bytes (including precompressed fonts/images)')
